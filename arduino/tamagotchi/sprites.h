/**
 * sprites.h - OLED bitmap sprites for Aritamaguchi (Arduino)
 *
 * Target: SSD1306 128×64 OLED (I²C / SPI)
 * Sprite size: 32×32 pixels = 128 bytes per frame
 * Format: Adafruit GFX compatible (row-major, MSB first)
 *
 * All data stored in PROGMEM to preserve precious SRAM.
 * (ATmega328P: 2KB SRAM, 32KB flash)
 *
 * Sprites represent:
 *   idle, happy, hungry, eating, sleeping, cleaning, sad, walking
 * Each has 2 animation frames.
 *
 * The character is a round blob-cat (32×32):
 *   Row 0-2:   Cat ears (triangles)
 *   Row 3-12:  Head (circle)
 *   Row 3-5:   Eyes
 *   Row 7:     Mouth
 *   Row 8-12:  Cheeks / chin
 *   Row 13-20: Body
 *   Row 21-26: Arms (side nubs)
 *   Row 27-31: Legs / feet
 */

